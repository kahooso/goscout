def main():
    stamp = time.strftime("%H%M%S")
    shutil.copy(DOCX, BACKUP_DIR / f"lab4_before_sborka_{stamp}.docx")
    doc = docx.Document(str(DOCX))
    body = doc.element.body

    start = next(p for p in doc.paragraphs
                 if p.style.name == "ОТЧЁТ_Заголовок_1" and p.text.strip() == "Ход работы")
    el = start._p
    sect = body.find(qn("w:sectPr"))
    while el is not None and el is not sect:
        nxt = el.getnext()
        body.remove(el)
        el = nxt

    fix_head(doc)
    fix_numbering(doc)

    items = content()
    # номера: глава «Ход работы» = 3
    fig_no, tbl_no, nf, nt = {}, {}, 0, 0
    for it in items:
        if it[0] == "fig":
            nf += 1
            fig_no[it[1]] = f"3.{nf}"
        elif it[0] == "tbl":
            nt += 1
            tbl_no[it[1]] = f"3.{nt}"
    refs = {**fig_no, **tbl_no}

    doc.add_paragraph("Ход работы", style="ОТЧЁТ_Заголовок_1")
    for it in items:
        kind = it[0]
        if kind == "h2":
            doc.add_paragraph(it[1], style="ОТЧЁТ_Заголовок_2")
        elif kind == "p":
            add_text(doc, it[1].format(**refs))
        elif kind == "eq":
            add_eq(doc, it[1])
        elif kind == "fig":
            _, key, src, cap = it
            label = src if isinstance(src, str) else key
            add_fig(doc, src, cap, f"{label}: рисунок {fig_no[key]}")
        elif kind == "tbl":
            add_table(doc, it[2], it[3])

    doc.add_paragraph("Выводы", style="ОТЧЁТ_Заголовок_1")
    for i, v in enumerate(VYVODY, 1):
        add_text(doc, f"{i}. {v}")

    doc.save(str(DOCX))
    missing = [k for k, (p, _) in SKRINY.items() if p is None]
    print("рисунков:", nf, "таблиц:", nt, "нет скринов:", len(missing))
    for key, no in fig_no.items():
        print(f"  {no}  {key}")


if __name__ == "__main__":
    main()
