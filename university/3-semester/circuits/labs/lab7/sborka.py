def grafik(name, xs, series, xlabel, ylabel, logx=True, logy=False, marks=None):
    path = LAB / name
    fig, ax = plt.subplots(figsize=(7, 4.5), dpi=150)
    for k, (lab, ys) in enumerate(series):
        ax.plot(xs, ys, marker=MARK[k], color=CVET[k], lw=2, ms=5, label=lab)
    if logx:
        ax.set_xscale("log")
    if logy:
        ax.set_yscale("log")
    else:
        ax.set_ylim(bottom=0)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(True, which="both", color="#d9d9d6", lw=0.6)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    zap = matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g}".replace(".", ","))
    ax.xaxis.set_major_formatter(zap)
    ax.yaxis.set_major_formatter(zap)
    for (x, y, txt) in marks or []:
        ax.axhline(y, color="#8a8986", lw=1, ls="--")
        ax.annotate(txt, (x, y), xytext=(4, 4), textcoords="offset points",
                    fontsize=8, color="#52514e")
    if len(series) > 1:
        ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


