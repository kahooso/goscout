def f(x, nd=3):
    return f"{x:.{nd}f}".replace(".", ",")


def g(x, sig=3):
    """sig значащих цифр, нули в конце сохраняются: 84 → 84,0"""
    if x == 0:
        return "0"
    s = f"{x:#.{sig}g}"
    if "e" in s:
        s = f"{x:.0f}"
    return s.rstrip(".").replace(".", ",")


def n(x):
    """целое или короткое число без лишних нулей: 2, 0,5"""
    return f"{x:g}".replace(".", ",")


def db(k):
    return 20 * math.log10(k)


def hz(x):
    """частота для таблиц: 100, 1 000 → «1 к» не используем — пишем в Гц/кГц по месту"""
    return n(x / 1e3) + " к" if x >= 1e3 else n(x)


def kgc(x, nd=2):
    return f(x / 1e3, nd)


def cap(c):
    """ёмкость словами: 5 нФ, 1 мкФ"""
    if c == 0:
        return "без C4"
    if c >= 1e-6:
        return n(round(c * 1e6, 3)) + " мкФ"
    return n(round(c * 1e9, 3)) + " нФ"


def kom(r):
    return n(r / 1e3) + " кОм"


