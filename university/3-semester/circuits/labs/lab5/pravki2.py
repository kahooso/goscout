def main():
    shutil.copy(DOCX, LAB / f"{{STUDENT_FILE}} Лаб5 — до правок {time.strftime('%H%M%S')}.docx")
    doc = docx.Document(str(DOCX))
    src = docx.Document(str(V3))

    set_par(find(doc, "Схема стенда приведена на рисунке 2.1"), T["pryam"])
    replace_in_par(find(doc, "Рабочая точка для каждого диода"), "R1 = 30 %", "R1 = 70 %")
    set_par(find(doc, "Переключатели S2 и S3 переведены"), T["obr"])
    set_par(find(doc, "D1: при U ="), T["after_37"])
    set_par(find(doc, "Ключом S6 выбран стабилитрон"), T["st"])
    replace_in_par(find(doc, "[СКРИН S07"), "R1 = 90 %", "R1 = 10 %")
    replace_in_par(find(doc, "[СКРИН S08"), "R1 = 20 %", "R1 = 80 %")

    # таблицы 3.1, 3.3, 3.4 (новые подписи % и новая 3.3)
    assert doc.tables[3].rows[0].cells[2].text == "I, мА" and len(doc.tables[3].columns) == 3
    for k in (0, 2, 3):
        copy_table(doc.tables[k], src.tables[k])

    # график 3.7: подменить картинку в том же месте (тот же размер в документе)
    ps = doc.paragraphs
    cap = next(i for i, p in enumerate(ps) if p.text.strip() == "– Обратные ветви ВАХ диодов D1 и D2")
    rid = ps[cap - 1]._p.xpath(".//a:blip/@r:embed")[0]
    doc.part.related_parts[rid]._blob = (LAB / "grafik_2_obratnye.png").read_bytes()

    # рисунок 3.5: скрин вместо жёлтой пометки, ширина как у рисунка 3.1
    ref = next(i for i, p in enumerate(ps) if p.text.strip() == "– Прямое включение диода D1 (1BH62)")
    cx = int(ps[ref - 1]._p.xpath(".//wp:extent/@cx")[0])
    p35 = find(doc, "[СКРИН S06")
    for r in list(p35.runs):
        r._r.getparent().remove(r._r)
    p35.add_run().add_picture(str(SKRIN_35), width=Emu(cx))

    doc.save(str(DOCX))
    print("ok")


if __name__ == "__main__":
    main()
