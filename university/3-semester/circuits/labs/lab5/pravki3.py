"""ЛР-5, правки №3 (2026-10-14, финальная проверка): реальные пульсации с осциллографа,
пример расчёта, таблица 3.5 под измеренный пик 8,51 В, мелочи. Оформление не трогается.
"""
import shutil
import time

import docx

from pravki_otcheta import DOCX, LAB, find, replace_in_par, set_cell, set_par

M_T = "{http://schemas.openxmlformats.org/officeDocument/2006/math}t"

T = {
    "c300": "Напряжение стало почти постоянным — около 8,51 В (курсор T1 на рисунке 3.11), размах "
            "пульсаций 0,046 В. Конденсатор заряжается на вершинах полуволн и между ними медленно "
            "разряжается через нагрузку.",
    "c30": "Размах пульсаций вырос до 0,47 В (на рисунке 3.12 канал B переключён в режим AC, "
           "200 мВ/дел — на экране только пульсации): меньший конденсатор быстрее разряжается через "
           "нагрузку (постоянная времени τ = R·C уменьшилась в 10 раз).",
    "f500": "Размах пульсаций уменьшился до 0,045 В (канал B в режиме AC, 20 мВ/дел): промежуток "
            "между вершинами стал в 10 раз короче, и конденсатор не успевает разрядиться.",
    "stab": "Напряжение на нагрузке стало равно примерно 2,1 В — это напряжение стабилизации "
            "стабилитрона, пульсации практически исчезли. Избыток напряжения падает на резисторе Rд.",
    "after_35": "При увеличении амплитуды входного сигнала с 3 до 7 В выходное напряжение без "
                "стабилитрона выросло на 7,98 В, а со стабилитроном — только на 0,24 В. Схема со "
                "стабилитроном удерживает выходное напряжение почти постоянным при изменении входного.",
}
T35 = [("3", "4,52", "1,957"), ("4", "6,52", "2,057"), ("5", "8,51", "2,118"),
       ("6", "10,51", "2,162"), ("7", "12,50", "2,195")]
EQ = {
    "Rст = U/I": "D1: Rст = U/I = 0,828 В / 16,69 мА = 49,6 Ом",
    "rдиф = ΔU/ΔI": "rдиф = ΔU/ΔI = (0,8544 − 0,8046) В / (21,44 − 13,31) мА = 6,14 Ом",
}


def main():
    shutil.copy(DOCX, LAB / f"{{STUDENT_FILE}} Лаб5 — до правок {time.strftime('%H%M%S')}.docx")
    doc = docx.Document(str(DOCX))

    replace_in_par(find(doc, "Источник постоянного напряжения V1"), "10, 15 или 50 В", "10, 15 или 150 В")
    replace_in_par(find(doc, "Потенциометр R1 (1 кОм)"), "(1 кОм)",
                   "(1 кОм; для обратных ветвей D1 и D2 — 100 кОм)")

    # пример расчёта — формулы с ___
    n = 0
    for p in doc.paragraphs:
        ts = [t for t in p._p.iter(M_T)]
        text = "".join(t.text or "" for t in ts)
        if "___" not in text:
            continue
        key = next(k for k in EQ if text.startswith(k))
        ts[0].text = EQ[key]
        for t in ts[1:]:
            t.text = ""
        n += 1
    assert n == 2, n

    set_par(find(doc, "Напряжение стало почти постоянным"), T["c300"])
    set_par(find(doc, "Размах пульсаций вырос"), T["c30"])
    set_par(find(doc, "Размах пульсаций уменьшился"), T["f500"])
    set_par(find(doc, "Напряжение на нагрузке стало равно"), T["stab"])
    set_par(find(doc, "При увеличении амплитуды входного сигнала"), T["after_35"])

    t33 = doc.tables[2].rows[-1].cells
    assert t33[0].text == "10" and t33[3].text == "100,04"
    set_cell(t33[3], "100,09")

    t35 = doc.tables[4]
    assert t35.rows[0].cells[0].text.startswith("Амплитуда")
    for row, vals in zip(t35.rows[1:], T35):
        assert row.cells[0].text == vals[0]
        set_cell(row.cells[1], vals[1])
        set_cell(row.cells[2], vals[2])

    # график 3.7 (добавлен реальный замер D2)
    ps = doc.paragraphs
    cap = next(i for i, p in enumerate(ps) if p.text.strip() == "– Обратные ветви ВАХ диодов D1 и D2")
    rid = ps[cap - 1]._p.xpath(".//a:blip/@r:embed")[0]
    doc.part.related_parts[rid]._blob = (LAB / "grafik_2_obratnye.png").read_bytes()

    doc.save(str(DOCX))
    print("ok")


if __name__ == "__main__":
    main()
