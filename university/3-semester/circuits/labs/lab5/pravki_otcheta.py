def set_par(p, text):
    runs = p.runs
    assert runs, p.text
    first = next((r for r in runs if r.text.strip() and r.text.strip() != "___"), runs[0])
    hl = first.font.highlight_color
    assert hl is None, ("первый run подсвечен", p.text[:60])
    first.text = text
    for r in runs:
        if r is not first:
            r._r.getparent().remove(r._r)


def replace_in_par(p, old, new):
    for r in p.runs:
        if old in r.text:
            r.text = r.text.replace(old, new)
            return
    raise AssertionError((old, p.text[:80]))


def set_cell(cell, text):
    par = cell.paragraphs[0]
    if par.runs:
        par.runs[0].text = text
        for r in par.runs[1:]:
            r._r.getparent().remove(r._r)
    else:
        par.add_run(text)


def copy_table(dst, src):
    assert len(dst.rows) == len(src.rows) and len(dst.columns) == len(src.columns), \
        (len(dst.rows), len(src.rows))
    for rd, rs in zip(dst.rows, src.rows):
        for cd, cs in zip(rd.cells, rs.cells):
            set_cell(cd, cs.text)


def find(doc, start):
    hits = [p for p in doc.paragraphs if p.text.strip().startswith(start)]
    assert len(hits) == 1, (start, len(hits))
    return hits[0]


