    set_par(find(doc, "На всех трёх графиках"), T["after_34"])
    set_par(find(doc, "Рабочая точка для каждого диода"), T["rab"])
    set_par(find(doc, "Статическое сопротивление в рабочей точке"), T["after_32"])
    set_par(find(doc, "Переключатели S2 и S3 переведены"), T["obr"])
    for code in ("[СКРИН S06", "[СКРИН S07"):
        replace_in_par(find(doc, code), "V1 = 50 В", "V1 = 150 В")
    set_par(find(doc, "D1: при U ="), T["after_37"])
    set_par(find(doc, "До напряжения пробоя ток стабилитрона"), T["after_39"])
    set_par(find(doc, "Напряжение стало почти постоянным"), T["c300"])
