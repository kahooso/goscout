    set_par(find(doc, "Размах пульсаций уменьшился"), T["f500"])
    set_par(find(doc, "Напряжение на нагрузке стало равно"), T["stab"])
    set_par(find(doc, "При увеличении амплитуды входного сигнала"), T["after_35"])
    set_par(find(doc, "1. Диод проводит ток"), T["v1"])
    set_par(find(doc, "4. Стабилитрон 02BZ2.2"), T["v4"])

