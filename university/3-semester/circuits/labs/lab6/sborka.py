def grafik(name, xs, series, xlabel, ylabel, label_x=None):
    path = LAB / name
    fig, ax = plt.subplots(figsize=(7, 4.5), dpi=150)
    for k, (lab, ys) in enumerate(series):
        ax.plot(xs, ys, marker=MARK[k], color=CVET[k], lw=2, ms=5, label=lab)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(True, color="#d9d9d6", lw=0.8)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.set_ylim(bottom=0)
    zap = matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g}".replace(".", ","))
    ax.xaxis.set_major_formatter(zap)
    ax.yaxis.set_major_formatter(zap)
    ax.legend(frameon=False)
    if label_x is not None:     # подписи у правого конца кривых
        for k, (lab, ys) in enumerate(series):
            ax.annotate(lab, (xs[-1], ys[-1]), xytext=(6, 0), textcoords="offset points",
                        va="center", fontsize=8, color="#52514e")
        ax.set_xlim(right=xs[-1] * label_x)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


