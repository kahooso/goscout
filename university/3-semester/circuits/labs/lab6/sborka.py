M_NS = "http://schemas.openxmlformats.org/officeDocument/2006/math"
W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
GRAFIKI = {}


def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def add_text(doc, text, style="Normal"):
    p = doc.add_paragraph(style=style)
    for part in re.split(r"(___|\[СКРИН[^\]]*\])", text):
        if not part:
            continue
        r = p.add_run(part)
        if part == NONE or part.startswith("["):
            r.font.highlight_color = WD_COLOR_INDEX.YELLOW
            r.bold = True
    return p


def add_eq(doc, parts, num):
    """parts: строки и (числитель, знаменатель); num — номер формулы или None"""
    xml = ""
    for part in parts:
        if isinstance(part, tuple):
            xml += (f"<m:f><m:num><m:r><m:t>{esc(part[0])}</m:t></m:r></m:num>"
                    f"<m:den><m:r><m:t>{esc(part[1])}</m:t></m:r></m:den></m:f>")
        else:
            xml += f'<m:r><m:t xml:space="preserve">{esc(part)}</m:t></m:r>'
    if num is not None:
        xml = (f"<m:eqArr><m:eqArrPr><m:maxDist m:val=\"1\"/></m:eqArrPr><m:e>{xml}"
               f"<m:r><m:t>#({num})</m:t></m:r></m:e></m:eqArr>")
    p = doc.add_paragraph(style="Normal")
    p._p.append(parse_xml(f'<m:oMathPara xmlns:m="{M_NS}"><m:oMath>{xml}'
                          f"</m:oMath></m:oMathPara>"))


def add_fig(doc, src, caption, label):
    p = doc.add_paragraph(style="ОТЧЁТ_Рисунок")
    if src in GRAFIKI:
        p.add_run().add_picture(str(GRAFIKI[src]), width=Cm(15))
    else:
        path, width, what = SKRINY[src]
        if path is not None and Path(path).exists():
            p.add_run().add_picture(str(path), width=Cm(width))
        else:
            r = p.add_run(f"[СКРИН {label}: {what}]")
            r.font.highlight_color = WD_COLOR_INDEX.YELLOW
            r.bold = True
    doc.add_paragraph("– " + caption, style="ОТЧЁТ_Рисунок_подпись")


def add_table(doc, caption, rows):
    cap = doc.add_paragraph(caption, style="ОТЧЁТ_Таблица_подпись")
    cap.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = doc.styles["ОТЧЁТ_Таблица"]
    t.autofit = False
    ncol = len(rows[0])
    first = 6.0 if rows[0][0].startswith("Схема") else 2.5
    widths = [first] + [(17.0 - first) / (ncol - 1)] * (ncol - 1)
    t._tbl.tblPr.append(parse_xml(
        f'<w:tblBorders xmlns:w="{W_NS}">'
        + "".join(f'<w:{b} w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
                  for b in ("top", "left", "bottom", "right", "insideH", "insideV"))
        + "</w:tblBorders>"))
    for gc, wcm in zip(t._tbl.tblGrid.findall(qn("w:gridCol")), widths):
        gc.set(qn("w:w"), str(int(wcm * 567)))
    for i, row in enumerate(rows):
        for j, txt in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths[j])
            par = cell.paragraphs[0]
            pf = par.paragraph_format
            pf.first_line_indent = Cm(0)
            pf.left_indent = Cm(0)
            par.alignment = 1
            r = par.add_run(txt)
            if i == 0:
                r.bold = True


def titul(doc):
    for p in doc.paragraphs[:25]:
        for r in p.runs:
            if p.text.startswith("ЛАБОРАТОРНАЯ РАБОТА №") and r.text.strip() == "5":
                r.text = "6"
            elif r.text == "ПОЛУПРОВОДНИКОВЫЕ ДИОДЫ":
                r.text = "БИПОЛЯРНЫЕ ТРАНЗИСТОРЫ"


def drop_unused_images(doc):
    body_xml = doc.element.xml
    part = doc.part
    for rid, rel in list(part.rels.items()):
        if "image" in rel.reltype and f'"{rid}"' not in body_xml:
            del part.rels[rid]


