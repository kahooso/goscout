def f(x, nd=3):
    return f"{x:.{nd}f}".replace(".", ",")


def g(x, sig=3):
    """sig значащих цифр, нули в конце сохраняются: 84 → 84,0"""
    if x == 0:
        return "0"
    s = f"{x:#.{sig}g}"
    if "e" in s:
        s = f"{x:.0f}"
    return s.rstrip(".").replace(".", ",")


def n(x):
    """целое или короткое число без лишних нулей: 2, 0,5"""
    return f"{x:g}".replace(".", ",")


def db(k):
    return 20 * math.log10(k)


def pr(d):
    return f"{d * 100:.0f} %"


