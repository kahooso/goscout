def oformit(fig, ax, path, legend):
    ax.grid(True, which="both", color="#d9d9d6", lw=0.6)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.xaxis.set_major_formatter(ZAP)
    ax.yaxis.set_major_formatter(ZAP)
    if legend:
        ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


