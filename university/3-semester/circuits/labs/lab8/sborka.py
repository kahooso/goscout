def grafik_vremya(name, rows, cols, ylabel="U, В", t_ms=True, t0=None, t1=None):
    """rows: [(t, y1, y2, …)], cols: [(индекс, подпись)]"""
    path = LAB / name
    fig, ax = plt.subplots(figsize=(7, 4), dpi=150)
    tt = [r[0] for r in rows]
    base = tt[0] if t0 is None else t0
    m = [i for i, t in enumerate(tt) if (t1 is None or t <= t1) and t >= base]
    for k, (j, lab) in enumerate(cols):
        ax.plot([(tt[i] - base) * 1e3 for i in m], [rows[i][j] for i in m],
                color=CVET[k], lw=1.6, label=lab)
    ax.axhline(0, color="#8a8986", lw=0.8)
    ax.set_xlabel("t, мс")
    ax.set_ylabel(ylabel)
    return oformit(fig, ax, path, len(cols) > 1)


