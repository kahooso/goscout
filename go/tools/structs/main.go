package main

import "fmt"

func main() {
	tasks := []*Task{
		NewTask(0, "Купить хлеб"),
		NewTask(1, "Написать код"),
		NewTask(2, "Лечь спать"),
	}
	// var tasks []*Task = []*Task{...} — C-стиль, в Go избыточен.
	// Go выводит тип из правой части через :=
	// Подробнее о := vs var: короткое объявление := используется внутри функций,
	// var — на уровне пакета или когда нужно явно указать тип без значения.

	tasks[0].Complete()
	PrintAll(tasks)
}

// Task — модель задачи.
//
// Аналог на C:
//   typedef struct { int id; char *title; int is_done; } Task;
//
// Go structs — это буквально C structs.
// Главное отличие от C++: методы определяются СНАРУЖИ структуры, через receiver.
// В C ты передавал Task* первым аргументом вручную — в Go то же самое,
// просто вынесено в синтаксис: func (t *Task) Method() вместо void method(Task *t).
type Task struct {
	ID     int
	Title  string
	IsDone bool
}

// NewTask — конструктор. В Go конструктор — это просто функция, возвращающая *T.
// Возвращаем *Task (указатель), чтобы методы с pointer receiver могли менять поля.
// IsDone не указываем явно — нулевое значение bool в Go уже false (как 0 в C).
func NewTask(id int, title string) *Task {
	return &Task{
		ID:    id,
		Title: title,
	}
}

// Complete помечает задачу выполненной.
//
// Pointer receiver (t *Task): метод получает указатель на оригинал — как Task* в C.
// Аналог на C: void task_complete(Task *t) { t->is_done = true; }
// Go добавляет синтаксический сахар: вместо task_complete(&myTask) пишешь myTask.Complete().
//
// Value receiver (t Task) здесь был бы ошибкой:
// метод получил бы КОПИЮ структуры. Изменение IsDone затронуло бы только копию
// и потерялось бы при выходе из функции — как передача Task по значению в C.
//
// Complete не возвращает error: операция не может провалиться.
// Error возвращают только когда что-то МОЖЕТ пойти не так по внешней причине —
// файл не открылся, сеть упала, данные невалидны. Поставить true не может провалиться.
// Правило: если функция всегда успешна — не возвращай error.
//
// Nil-check убран: в Go не принято защищаться от nil receiver в бизнес-методах.
// Вызов Complete() на nil-указателе — ошибка вызывающего кода, не этого метода.
// Исключение: некоторые типы из stdlib намеренно поддерживают nil receiver (редко).
func (t *Task) Complete() {
	t.IsDone = true
}

// String возвращает строковое представление: "[x] 0. Купить хлеб"
//
// "Подстановки в строку" в Go — это fmt.Sprintf.
// Аналоги в других языках: f"..." в Python, `${var}` в JS, sprintf в C.
// В Go нет встроенного синтаксиса для string interpolation — только fmt.Sprintf.
//
// Спецификаторы формата:
//   %d  — int:    42
//   %s  — string: hello
//   %t  — bool:   true / false
//   %f  — float:  3.14
//   %v  — любой тип (дефолтный вид): {1 Купить хлеб false}
//   %+v — struct с именами полей:    {ID:1 Title:Купить хлеб IsDone:false}
//   %T  — тип значения:              *main.Task
//   %p  — адрес указателя:           0xc000014080
//
// Value receiver здесь ок — метод только читает, не меняет структуру.
// Nil-check убран — по той же причине что в Complete.
func (t *Task) String() string {
	sgn := " "
	if t.IsDone {
		sgn = "x"
	}
	return fmt.Sprintf("[%s] %d. %s", sgn, t.ID, t.Title)
}

// ЛИШНИЙ МЕТОД: Print() дублирует логику String() и нигде не используется.
// В Go неиспользуемый публичный метод — это обязательство для всех, кто импортирует пакет.
// Если метод не нужен — удалить. Лишний код хуже, чем его отсутствие.
func (t *Task) Print() {
	fmt.Printf("ID: %d, Title: %s, IsDone: %t\n", t.ID, t.Title, t.IsDone)
}

// PrintAll печатает все задачи.
//
// fmt.Println(t) автоматически вызывает t.String(), если тип реализует
// интерфейс fmt.Stringer — то есть имеет метод String() string.
// Явный вызов t.String() не нужен. Это пример интерфейса в действии — тема A0.8.
//
// []*Task vs []Task:
//   []Task   — слайс структур. Каждый элемент — копия Task.
//   []*Task  — слайс указателей на Task. Каждый элемент — адрес Task в куче.
//   [][]Task — двумерный слайс (слайс слайсов). Это ДРУГАЯ вещь — не путать.
//
// []*Task ≠ [][]Task — это была неверная аналогия. Поправка:
//   *Task — указатель на Task (один уровень косвенности, как Task* в C)
//   **Task — указатель на указатель (два уровня, как Task** в C)
//   [][]Task — это не указатели вообще, это вложенные слайсы
//
// Модель памяти []*Task:
//   Заголовок слайса (len, cap, ptr) — на стеке.
//   Массив указателей — в куче (backing array слайса).
//   Каждая Task — отдельно в куче, указатели ссылаются на неё.
//
// Здесь []*Task правильный выбор: Complete() меняет структуры через pointer receiver,
// значит нужны указатели на оригиналы, а не копии.
func PrintAll(tasks []*Task) {
	for _, t := range tasks {
		fmt.Println(t)
	}
}
