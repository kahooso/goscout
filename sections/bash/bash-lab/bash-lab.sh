#!/bin/bash
set -euo pipefail
# bash-lab v1.1 — PT Guided Case 1.4 + режимы errors/top, строгий режим, коды возврата

script_name="bash-lab"
version="1.1"
report_file="report.txt"
error_file="error.log"
ip_pattern='([0-9]{1,3}\.){3}[0-9]{1,3}'

print_usage() {
    echo "Usage: $0 <mode> <log-file> [limit]"
    echo
    echo "Modes:"

    for mode_name in info preview scan errors top report help; do
        echo "- $mode_name"
    done

    echo
    echo "Examples:"
    echo "  $0 info sample.log"
    echo "  $0 preview sample.log 10"
    echo "  $0 scan sample.log"
    echo "  $0 errors sample.log"
    echo "  $0 top sample.log"
    echo "  $0 report sample.log"
}

err() {
    echo "Error: $1" >&2
    exit 1
}

require_log_file() {
    local mode="$1"
    local file="$2"

    if [ -z "$file" ]; then
        err "log file is required for mode: $mode"
    fi

    if [ ! -f "$file" ]; then
        err "file not found: $file"
    fi

    if [ ! -r "$file" ]; then
        err "file is not readable: $file"
    fi
}

show_info() {
    local file="$1"
    local line_count

    line_count=$(wc -l < "$file")

    echo "$script_name version $version"
    echo "Target file: $file"
    echo "Lines: $line_count"
}

show_preview() {
    local file="$1"
    local limit="${2:-5}"
    local counter=0
    local line

    while IFS= read -r line; do
        counter=$((counter + 1))
        echo "$counter: $line"

        if [ "$counter" -ge "$limit" ]; then
            break
        fi
    done < "$file"
}

find_ips() {
    local file="$1"

    grep -Eo "$ip_pattern" "$file" || true
}

scan_ips() {
    local file="$1"
    local found

    found=$(find_ips "$file" | sort -u)

    if [ -z "$found" ]; then
        return 1
    fi

    echo "$found"
}

show_errors() {
    local file="$1"
    local count

    count=$(grep -c "ERROR" "$file" || true)

    echo "ERROR lines: $count"
}

show_top() {
    local file="$1"
    local limit="${2:-3}"

    find_ips "$file" | sort | uniq -c | sort -rn | head -n "$limit"
}

make_report() {
    local file="$1"

    {
        echo "Report for: $file"
        echo "Generated by: $script_name $version"
        echo "Lines: $(wc -l < "$file")"
        echo
        echo "Unique IP-like strings:"
        scan_ips "$file" || echo "(no IP-like strings found)"
    } > "$report_file" 2> "$error_file"

    echo "Report saved to: $report_file"
    echo "Errors saved to: $error_file"
}

mode="${1:-}"
target_file="${2:-}"
limit="${3:-5}"

if [ "$#" -eq 0 ]; then
    print_usage
    exit 1
fi

case "$mode" in
    help)
        print_usage
        ;;
    info)
        require_log_file "$mode" "$target_file"
        show_info "$target_file"
        ;;
    preview)
        require_log_file "$mode" "$target_file"
        show_preview "$target_file" "$limit"
        ;;
    scan)
        require_log_file "$mode" "$target_file"
        scan_ips "$target_file"
        ;;
    errors)
        require_log_file "$mode" "$target_file"
        show_errors "$target_file"
        ;;
    top)
        require_log_file "$mode" "$target_file"
        show_top "$target_file"
        ;;
    report)
        require_log_file "$mode" "$target_file"
        make_report "$target_file"
        ;;
    *)
        err "unknown mode: $mode"
        ;;
esac
